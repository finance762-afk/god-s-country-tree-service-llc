        <h2>How to tell them apart</h2>

        <h3>Leaves</h3>
        <ul>
          <li><strong>Live oak:</strong> thick, stiff, leathery leaves, dark green on top and paler and slightly fuzzy underneath. The edges often curl under a little.</li>
          <li><strong>Laurel oak:</strong> thinner, smoother, glossy leaves that are green on both sides, shaped a bit like a narrow laurel or bay leaf.</li>
        </ul>

        <h3>Bark</h3>
        <ul>
          <li><strong>Live oak:</strong> dark, rough and deeply furrowed into blocky ridges.</li>
          <li><strong>Laurel oak:</strong> smoother on younger trees, with shallower ridges as it ages.</li>
        </ul>

        <h3>Shape</h3>
        <ul>
          <li><strong>Live oak:</strong> wide and sprawling, often wider than it is tall, with long, low, curving limbs.</li>
          <li><strong>Laurel oak:</strong> taller than it is wide, with a denser, oval canopy and a more upright trunk.</li>
        </ul>

        <h3>Leaf drop</h3>
        <ul>
          <li><strong>Live oak</strong> stays green through the year and swaps its old leaves for new ones quickly in spring.</li>
          <li><strong>Laurel oak</strong> is semi-evergreen and often looks thin or bare for a stretch in late winter before the new leaves come in.</li>
        </ul>

        <h2>Why laurel oaks need a closer look</h2>
        <p>UF/IFAS notes that even a small trunk wound or a bad pruning cut on a laurel oak can lead to a column of decay <strong>10, 20 or more feet long</strong> inside the trunk. A study of Tampa street trees found decay in about <strong>two-thirds of the large laurel oaks tested, compared with under a third of the live oaks.</strong></p>
        <p>That doesn't mean every laurel oak is dangerous. It means a mature laurel oak, especially one that's 40 years or older or growing over a house, driveway or play area, is worth having checked.</p>

        <h2>Signs your laurel oak may be in decline</h2>
        <ul>
          <li>Mushrooms or conks growing on the trunk or at the base</li>
          <li>Hollow-sounding spots, cavities or open wounds on the trunk</li>
          <li>Large dead limbs in the upper canopy</li>
          <li>Cracks where big limbs join the trunk</li>
          <li>Thinning leaves outside the normal late-winter drop</li>
        </ul>
        <p>See our full list of <a href="/blog/signs-dangerous-tree-deland/">signs of a dangerous tree</a>.</p>

        <h2>Caring for each tree</h2>
        <ul>
          <li><strong>Live oak:</strong> give it room and prune it for good structure while it's young, so it develops well-spaced limbs.</li>
          <li><strong>Laurel oak:</strong> prune small branches regularly instead of cutting big limbs later, since large cuts invite decay. Have mature trees inspected every few years.</li>
        </ul>

        <p><strong>Sources:</strong> UF/IFAS ST549 (laurel oak); UF/IFAS ST564 (southern live oak); Koeser et al., Arboriculture &amp; Urban Forestry 42(4), 2016 (Tampa decay study).</p>

