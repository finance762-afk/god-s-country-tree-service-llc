        <p class="lead">A pine that turns brown is often already dying. As UF/IFAS and the Florida Forest Service explain, needles usually fade from green to yellow to reddish-brown, and by the time the whole crown is brown, any beetles involved have often already left. The good news is that the pattern of browning, and a few quick checks on the trunk, tell you a lot.</p>

