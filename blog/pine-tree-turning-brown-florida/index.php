        <h2>Step 1: Look at the pattern</h2>
        <ul>
          <li><strong>The whole crown is fading at once.</strong> This is the most serious pattern. It usually points to bark beetles, root problems, lightning or a hard drought, and the tree is often past saving.</li>
          <li><strong>Browning from the top down.</strong> Often a sign of stress, such as lightning, drought or root damage, and beetles may follow.</li>
          <li><strong>Scattered brown branches.</strong> Could be broken limbs, minor disease or localized damage. Worth watching, but less urgent.</li>
          <li><strong>Only the oldest, inner needles are browning in fall.</strong> This is usually normal seasonal needle drop, not a problem.</li>
        </ul>

        <h2>Step 2: Check the trunk</h2>
        <ul>
          <li><strong>Pitch tubes:</strong> small blobs of whitish or reddish resin, usually under about an inch across, where beetles have bored in.</li>
          <li><strong>Boring dust:</strong> reddish-brown sawdust on the bark, in crevices or at the base of the tree.</li>
          <li><strong>Tiny exit holes:</strong> small round holes, 1 to 3 mm across, where beetles have come out.</li>
          <li><strong>Galleries under loose bark:</strong> tunnels in the inner bark. Y-, I- or H-shaped tunnels point to Ips engraver beetles. Winding S-shaped tunnels that cross each other point to the southern pine beetle.</li>
        </ul>

        <h2>Step 3: Figure out if nearby pines are at risk</h2>
        <ul>
          <li><strong>Ips engraver beetles</strong> are the most common culprits in Florida. They usually attack pines already stressed by drought, flooding, lightning, storm damage or root disturbance. According to UF/IFAS, they don't usually spread to healthy neighboring pines.</li>
          <li><strong>The southern pine beetle</strong> is rarer, but it's the only bark beetle in Florida that can spread fast and kill nearby healthy pines. Signs are many popcorn-like resin lumps in the crevices of the bark and winding S-shaped tunnels underneath. UF/IFAS advises homeowners north of Orlando, which includes Volusia County, to remove an infested tree right away and contact their county Extension office or the Florida Forest Service.</li>
        </ul>

        <h2>Common stressors that start the problem</h2>
        <ul>
          <li>Drought, or a long dry spell</li>
          <li>Lightning strikes</li>
          <li>Root damage from construction, trenching or new driveways</li>
          <li>Soil filled or piled over the roots</li>
          <li>Flooding or standing water</li>
        </ul>

        <h2>When to call</h2>
        <p>Call for an inspection if the crown is turning brown fast, you see pitch tubes or boring dust, or the pine is close enough to hit your house, a driveway or a power line. A dead pine dries out and gets brittle quickly, which makes it riskier and harder to take down the longer it stands.</p>

