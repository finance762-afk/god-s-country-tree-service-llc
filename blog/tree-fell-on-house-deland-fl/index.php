        <h2>Step 1: Is the House Safe to Stay In?</h2>
        <p>The house is safe to stay in only if the tree is clear of the rooms you are using and nothing structural has moved. Clear the room under the strike first. If you see ceiling sag, new drywall cracks, doors that suddenly won't close, or any shifting, get everyone out of the house.</p>
        <p>A trunk resting on a roof is not stable. It can shift, roll, or punch deeper through the decking without warning, so get people away from the impact zone before anyone thinks about the tree.</p>
        <p>Two hazards outrank the tree itself. First, downed or sagging power lines. A service drop torn off the house by a falling limb can leave an energized line lying in wet grass. Treat every downed line as live, keep everyone well back, and report it to your power company (Duke Energy serves much of DeLand) before any crew starts work. Second, gas. If you smell gas anywhere in the house, leave immediately, don't flip switches or light anything, and call your gas provider and 911 from outside. A crushed roofline can shear vent stacks and appliance connections you can't see from the yard.</p>

        <h2>Step 2: Why Document Everything Before Any Work Starts?</h2>
        <p>Document everything before any work starts because the insurance adjuster reconstructs what happened from your photos and video. Once the scene is safe, shoot the tree, the roof, the interior damage, and the yard from several angles. A tree already cut up is much harder to claim than one on camera.</p>
        <p>One point of confusion worth clearing up: in most cases, your own homeowner's policy is the one that responds when a tree lands on your house, even when the tree grew in your neighbor's yard. Liability generally shifts only in specific circumstances, such as a documented pre-existing hazard, so don't burn hours arguing over the fence line while water pours into your attic. File under your own policy, keep every photo and invoice, and let the insurers sort out the rest. For a full walkthrough of how claims, deductibles, and removal coverage work, read our guide to <a href="/blog/insurance-fallen-tree-removal-florida/">what Florida homeowners insurance covers for fallen tree removal</a>.</p>

        <h2>Step 3: How Do You Stop Water From Pouring In?</h2>
        <p>Stop water from pouring in by getting the hole in the roof tarped, on the day of the strike whenever conditions allow. Often the tree, or part of it, has to come off the roof before a tarp can seal the breach, so tarping and tree removal are usually coordinated as one emergency response.</p>
        <p>Water intrusion is the clock that is always running on a tree strike in Central Florida. A punctured roof in DeLand rarely gets a dry grace period: summer afternoon thunderstorms roll through almost daily from June into September, and hurricane season runs June through November. The tree does its damage in seconds; the rain that follows can soak insulation, drywall, flooring, and wiring for days if the hole stays open.</p>
        <p>Document the damage first (Step 2), then get the roof covered. Your insurer expects you to take reasonable steps to prevent further damage, and a properly secured tarp is exactly that.</p>

