          <h3>Quick Answer: What does a certified arborist do?</h3>
          <p>A certified arborist assesses tree health and structure, diagnoses pests and diseases, prunes to ANSI A300 standards, evaluates the risk of failure, and makes save-vs-remove calls. The ISA credential requires documented tree care experience, a comprehensive exam, and ongoing continuing education. Call one for hazard assessments, sick trees, and any removal near a structure.</p>
